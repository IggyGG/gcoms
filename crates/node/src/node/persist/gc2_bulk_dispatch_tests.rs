fn gc2_dispatch_body(kind: &str, index: u8) -> Vec<u8> {
    let mut application = b"GCAPP1".to_vec();
    application.extend_from_slice(&(kind.len() as u16).to_be_bytes());
    application.extend_from_slice(kind.as_bytes());
    application.push(index);
    gcoms_core::component::RoutedApplication {
        source: [11; 16],
        destination: [12; 16],
        application,
    }
    .encode()
    .unwrap()
}

#[tokio::test]
async fn gc2_bulk_dispatch_fills_credit_while_preserving_control_and_total_quota() {
    let (alice, mut bob, _) = gc2_recovery_pair(101, 102).await;
    let (events, _) = broadcast::channel(32);
    gc2_credit_initial_ack(&alice, &mut bob, &events);
    for index in 0..32 {
        prepare_volatile_application(
            &alice,
            &bob.info,
            &gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, index),
        )
        .unwrap();
    }
    let before = {
        let a = alice.lock().unwrap();
        (
            a.next_direct_sequence,
            a.sessions[&bob.info.identity_pk].send_ctr(),
        )
    };
    assert!(prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 32),
    )
    .err()
    .unwrap()
    .contains("volatile outbox quota exceeded"));
    {
        let a = alice.lock().unwrap();
        assert_eq!(
            before,
            (
                a.next_direct_sequence,
                a.sessions[&bob.info.identity_pk].send_ctr()
            )
        );
    }
    // Real authenticated application classification, not a caller-selected
    // traffic flag, protects the bootstrap reply from 32 pending chunks.
    for index in 0..8 {
        prepare_volatile_application(
            &alice,
            &bob.info,
            &gc2_dispatch_body(gcoms_core::bootstrap::CONTENT_TYPE, index),
        )
        .expect("pending file data must leave the control reservation available");
    }
    assert!(prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::bootstrap::CONTENT_TYPE, 8),
    )
    .err()
    .unwrap()
    .contains("volatile outbox quota exceeded"));
    let mut a = alice.lock().unwrap();
    assert_eq!(a.pending_1to1.len(), 40);
    // Fill the global bound with copies of existing retained metadata; no
    // packets or counters are generated by this quota-boundary fixture.
    let original = a.pending_1to1.values().next().unwrap();
    let template = (
        original.delivery.clone(),
        original.logical_record.clone(),
        original.sequence,
        original.next_attempt,
        original.expires,
        original.application_event,
    );
    for index in 40..64u8 {
        let mut pending = PendingDirect {
            delivery: template.0.clone(),
            logical_record: template.1.clone(),
            sequence: template.2,
            next_attempt: template.3,
            expires: template.4,
            application_event: template.5,
        };
        pending.delivery.peer.identity_pk = vec![index; 32];
        a.pending_1to1.insert([index; 16], pending);
    }
    assert_eq!(a.pending_1to1.len(), 64);
    drop(a);
    assert!(prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::bootstrap::CONTENT_TYPE, 9),
    )
    .err()
    .unwrap()
    .contains("volatile outbox quota exceeded"));
    alice.lock().unwrap().scheduler.shutdown();
    bob.scheduler.shutdown();
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn gc2_bulk_dispatch_admits_next_chunk_while_own_hop_reply_is_pending() {
    use bytes::Bytes;
    use gcoms_core::gc2::NaturalCell;
    use gcoms_protocol::relay::gc2::Push;
    use tokio::net::TcpListener;
    use tokio_rustls::TlsAcceptor;

    let (alice, mut bob, _) = gc2_recovery_pair(103, 104).await;
    let (events, _) = broadcast::channel(32);
    gc2_credit_initial_ack(&alice, &mut bob, &events);
    let identity = TlsIdentity::generate().unwrap();
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    bob.info.aliases[0].target = RelayTarget {
        address: listener.local_addr().unwrap(),
        relay_service_id: identity.service_id(),
    };
    bob.info.aliases[0].expiry = now_unix() + 3600;
    let expected = bob.info.aliases[0].clone();
    let acceptor = TlsAcceptor::from(Arc::new(identity.server_config().unwrap()));
    let (observed, mut received) = mpsc::channel(8);
    let server = tokio::spawn(async move {
        let (tcp, _) = listener.accept().await.unwrap();
        let tls = acceptor.accept(tcp).await.unwrap();
        let mut connection = h2::server::handshake(tls).await.unwrap();
        let mut requests = tokio::task::JoinSet::new();
        while let Some(Ok((request, mut reply))) = connection.accept().await {
            let expected = expected.clone();
            let observed = observed.clone();
            requests.spawn(async move {
                assert_eq!(
                    request.uri().path(),
                    format!("/gc2/{}", encode_b64url(&expected.queue_id))
                );
                let mut body = request.into_body();
                let mut wire = Vec::new();
                while let Some(Ok(bytes)) = body.data().await {
                    body.flow_control().release_capacity(bytes.len()).unwrap();
                    wire.extend_from_slice(&bytes);
                }
                let cell = NaturalCell::decode(&wire).unwrap();
                let push = Push::decode(
                    &cell,
                    &expected.push_cap,
                    &expected.target.relay_service_id,
                    now_unix(),
                )
                .unwrap();
                let send = reply.send_response(http::Response::new(()), false).unwrap();
                observed
                    .send((push.class, push.msg.unwrap(), send))
                    .await
                    .unwrap();
            });
            while requests.try_join_next().is_some() {}
        }
        requests.shutdown().await;
    });
    let client = Arc::new(Tp1Client::new().unwrap());
    let scheduler = RelayScheduler::with_gc2_client(client.clone());
    {
        let mut a = alice.lock().unwrap();
        a.scheduler.shutdown();
        a.scheduler = scheduler.clone();
        a.gc2_carrier_client = Some(client);
    }
    let (commands, cmd_rx) = mpsc::channel(8);
    let command_loop = commands::spawn_command_loop(commands::CommandLoopContext {
        state: alice.clone(),
        frwd_admitted: Default::default(),
        scheduler: scheduler.clone(),
        events_tx: events.clone(),
        #[cfg(feature = "relay-host")]
        relay_host: None,
        cmd_rx,
    });
    let (done, mut first_result) = tokio::sync::oneshot::channel();
    commands
        .send(Cmd::SendVolatileApplication {
            peer: Box::new(bob.info.clone()),
            body: gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 1).into(),
            done,
        })
        .await
        .unwrap();
    let (first_class, first, mut first_reply) =
        tokio::time::timeout(std::time::Duration::from_secs(5), received.recv())
            .await
            .unwrap()
            .unwrap();
    let (done, second_result) = tokio::sync::oneshot::channel();
    commands
        .send(Cmd::SendVolatileApplication {
            peer: Box::new(bob.info.clone()),
            body: gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 2).into(),
            done,
        })
        .await
        .unwrap();
    let (second_class, second, mut second_reply) =
        tokio::time::timeout(std::time::Duration::from_secs(2), received.recv())
            .await
            .expect("next bulk deposit must be admitted before the prior hop responds")
            .unwrap();
    assert_eq!(first_class, gcoms_core::TrafficClass::Bulk);
    assert_eq!(second_class, gcoms_core::TrafficClass::Bulk);
    assert!(matches!(
        first_result.try_recv(),
        Err(tokio::sync::oneshot::error::TryRecvError::Empty)
    ));
    let accepted = NaturalCell::new(
        gcoms_core::CellType::Ack,
        0,
        vec![
            gcoms_core::hop::HOP_REPLY_VERSION,
            gcoms_core::hop::HopReply::Accepted.code(),
        ],
    )
    .unwrap()
    .encode();
    second_reply
        .send_data(Bytes::from(accepted.clone()), true)
        .unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(2), second_result)
        .await
        .unwrap()
        .unwrap()
        .unwrap();
    assert!(matches!(
        first_result.try_recv(),
        Err(tokio::sync::oneshot::error::TryRecvError::Empty)
    ));
    // The authenticated receiver can credit reordered chunk counters while
    // both originals remain in the sender's logical outbox until that credit.
    gc2_direct::incoming(&mut bob, second.payload(), &events).unwrap();
    gc2_direct::incoming(&mut bob, first.payload(), &events).unwrap();
    assert_eq!(alice.lock().unwrap().pending_1to1.len(), 2);
    let (done, third_result) = tokio::sync::oneshot::channel();
    commands
        .send(Cmd::SendVolatileApplication {
            peer: Box::new(bob.info.clone()),
            body: gc2_dispatch_body(gcoms_core::VOLATILE_FILE_ACK_CONTENT_TYPE, 3).into(),
            done,
        })
        .await
        .unwrap();
    let (third_class, _, mut third_reply) =
        tokio::time::timeout(std::time::Duration::from_secs(2), received.recv())
            .await
            .unwrap()
            .unwrap();
    assert_eq!(third_class, gcoms_core::TrafficClass::Interactive);
    let (done, fourth_result) = tokio::sync::oneshot::channel();
    commands
        .send(Cmd::SendVolatileApplication {
            peer: Box::new(bob.info.clone()),
            body: gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 4).into(),
            done,
        })
        .await
        .unwrap();
    assert!(
        tokio::time::timeout(std::time::Duration::from_millis(200), received.recv())
            .await
            .is_err(),
        "interactive completion still holds the next peer dispatch"
    );
    third_reply
        .send_data(Bytes::from(accepted.clone()), true)
        .unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(2), third_result)
        .await
        .unwrap()
        .unwrap()
        .unwrap();
    let (fourth_class, _, mut fourth_reply) =
        tokio::time::timeout(std::time::Duration::from_secs(2), received.recv())
            .await
            .unwrap()
            .unwrap();
    assert_eq!(fourth_class, gcoms_core::TrafficClass::Bulk);
    fourth_reply
        .send_data(Bytes::from(accepted.clone()), true)
        .unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(2), fourth_result)
        .await
        .unwrap()
        .unwrap()
        .unwrap();
    first_reply.send_data(Bytes::from(accepted), true).unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(2), first_result)
        .await
        .unwrap()
        .unwrap()
        .unwrap();
    let (done, stopped) = tokio::sync::oneshot::channel();
    commands.send(Cmd::Shutdown { done }).await.unwrap();
    stopped.await.unwrap();
    command_loop.await.unwrap();
    bob.scheduler.shutdown();
    server.abort();
    let _ = server.await;
}

#[tokio::test]
async fn gc2_bulk_dispatch_global_control_reservation_and_failed_save_are_bounded() {
    let (alice, mut bob, _) = gc2_recovery_pair(105, 106).await;
    let (events, _) = broadcast::channel(32);
    gc2_credit_initial_ack(&alice, &mut bob, &events);
    prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 0),
    )
    .unwrap();
    let before = {
        let mut a = alice.lock().unwrap();
        let original = a.pending_1to1.values().next().unwrap();
        let template = (
            original.delivery.clone(),
            original.logical_record.clone(),
            original.sequence,
            original.next_attempt,
            original.expires,
            original.application_event,
        );
        for index in 1..56u8 {
            let mut pending = PendingDirect {
                delivery: template.0.clone(),
                logical_record: template.1.clone(),
                sequence: template.2,
                next_attempt: template.3,
                expires: template.4,
                application_event: template.5,
            };
            pending.delivery.peer.identity_pk = vec![index; 32];
            a.pending_1to1.insert([index; 16], pending);
        }
        assert_eq!(a.pending_1to1.len(), 56);
        (
            a.next_direct_sequence,
            a.sessions[&bob.info.identity_pk].send_ctr(),
        )
    };
    assert!(prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::VOLATILE_FILE_CONTENT_TYPE, 1)
    )
    .err()
    .unwrap()
    .contains("volatile outbox quota exceeded"));
    {
        let a = alice.lock().unwrap();
        assert_eq!(
            before,
            (
                a.next_direct_sequence,
                a.sessions[&bob.info.identity_pk].send_ctr()
            )
        );
    }
    let control = prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::bootstrap::CONTENT_TYPE, 1),
    )
    .unwrap()
    .message_id;
    let (snapshot, mut ids) = {
        let mut a = alice.lock().unwrap();
        let original = &a.pending_1to1[&control];
        let template = (
            original.delivery.clone(),
            original.logical_record.clone(),
            original.sequence,
            original.next_attempt,
            original.expires,
            original.application_event,
        );
        // Leave one control slot available for the real failed checkpoint;
        // other peers' metadata isolates the global bound.
        for index in 56..62u8 {
            let mut pending = PendingDirect {
                delivery: template.0.clone(),
                logical_record: template.1.clone(),
                sequence: template.2,
                next_attempt: template.3,
                expires: template.4,
                application_event: template.5,
            };
            pending.delivery.peer.identity_pk = vec![index; 32];
            a.pending_1to1.insert([index; 16], pending);
        }
        assert_eq!(a.pending_1to1.len(), 63);
        let PeerSession::Credited(session) = &a.sessions[&bob.info.identity_pk] else {
            panic!("GC2")
        };
        let snapshot = (a.next_direct_sequence, session.window().encode_private());
        let ids: Vec<_> = a
            .pending_1to1
            .iter()
            .map(|(id, p)| (*id, p.sequence, p.expires, p.delivery.cells.clone()))
            .collect();
        a.durable_state_sink = Some(Arc::new(|_| {
            Err("control reservation checkpoint failure".into())
        }));
        (snapshot, ids)
    };
    assert!(prepare_volatile_application(
        &alice,
        &bob.info,
        &gc2_dispatch_body(gcoms_core::bootstrap::CONTENT_TYPE, 2)
    )
    .err()
    .unwrap()
    .contains("control reservation checkpoint failure"));
    let a = alice.lock().unwrap();
    let PeerSession::Credited(session) = &a.sessions[&bob.info.identity_pk] else {
        panic!("GC2")
    };
    assert_eq!(
        snapshot,
        (a.next_direct_sequence, session.window().encode_private())
    );
    let mut after: Vec<_> = a
        .pending_1to1
        .iter()
        .map(|(id, p)| (*id, p.sequence, p.expires, p.delivery.cells.clone()))
        .collect();
    ids.sort_by_key(|row| row.0);
    after.sort_by_key(|row| row.0);
    assert_eq!(ids, after);
    a.scheduler.shutdown();
    bob.scheduler.shutdown();
}
